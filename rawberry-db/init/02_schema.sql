-- =====================================================================
-- RAWberry schema (PostgreSQL + pgvector)
-- Includes Timeline support: full timestamps, time-ordered indexes,
-- and automatic session "last activity" tracking.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS vector;

-- ---------------------------------------------------------------------
-- Lookup tables
-- BY DEFAULT (not ALWAYS) so the seed rows below can use fixed IDs.
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL,

    CONSTRAINT uq_status
        UNIQUE (status)
);

CREATE TABLE IF NOT EXISTS role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,

    CONSTRAINT uq_role_name
        UNIQUE (name)
);

-- ---------------------------------------------------------------------
-- Documents and authors
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS author (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS document (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title TEXT NULL,
    header TEXT NULL,
    institution TEXT NULL,
    citation TEXT NULL,
    publish_date DATE NULL,                          -- stays DATE: a calendar date, not an event time
    status_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NULL,

    CONSTRAINT fk_document_status
        FOREIGN KEY (status_id)
        REFERENCES status(id)
);

CREATE TABLE IF NOT EXISTS document_author (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,

    CONSTRAINT fk_document_author_document
        FOREIGN KEY (document_id)
        REFERENCES document(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_document_author_author
        FOREIGN KEY (author_id)
        REFERENCES author(id),

    CONSTRAINT uq_document_author
        UNIQUE (document_id, author_id)
);

-- ---------------------------------------------------------------------
-- Chunks and embeddings (RAG)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chunk (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    doc_id BIGINT NOT NULL,
    chunk_index BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_chunk_document
        FOREIGN KEY (doc_id)
        REFERENCES document(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_chunk_index
        UNIQUE (doc_id, chunk_index)
);

CREATE TABLE IF NOT EXISTS embedding (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    chunk_id BIGINT NOT NULL,
    -- Set this to your embedding model's output size.
    -- A fixed dimension is required for the HNSW index below.
    vector VECTOR(768) NOT NULL,
    model TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_embedding_chunk
        FOREIGN KEY (chunk_id)
        REFERENCES chunk(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_embedding_chunk_model
        UNIQUE (chunk_id, model)
);

-- ---------------------------------------------------------------------
-- Chat sessions and messages (Timeline)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS chat_session (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    doc_id BIGINT NOT NULL,
    title TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),   -- last activity; bumped by trigger on new messages

    CONSTRAINT fk_chat_session_document
        FOREIGN KEY (doc_id)
        REFERENCES document(id)
);

CREATE TABLE IF NOT EXISTS message (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_message_session
        FOREIGN KEY (session_id)
        REFERENCES chat_session(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_message_role
        FOREIGN KEY (role_id)
        REFERENCES role(id)
);

CREATE TABLE IF NOT EXISTS citation (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL,
    chunk_id BIGINT NOT NULL,
    retrieval_score DECIMAL NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_citation_message
        FOREIGN KEY (message_id)
        REFERENCES message(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_citation_chunk
        FOREIGN KEY (chunk_id)
        REFERENCES chunk(id)
);

CREATE TABLE IF NOT EXISTS chat_session_access (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    is_deleted BOOL NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_chat_session_access_session
        FOREIGN KEY (session_id)
        REFERENCES chat_session(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_chat_session_access
        UNIQUE (user_id, session_id)
);

-- ---------------------------------------------------------------------
-- Indexes
-- ---------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_document_status_id
ON document(status_id);

-- (document_id, author_id) is already covered by uq_document_author
CREATE INDEX IF NOT EXISTS idx_document_author_author_id
ON document_author(author_id);

-- doc_id lookups are covered by uq_chunk_index (doc_id, chunk_index)

-- chunk_id lookups are covered by uq_embedding_chunk_model (chunk_id, model)

-- Vector similarity search (cosine, matches the <=> operator)
CREATE INDEX IF NOT EXISTS idx_embedding_vector_hnsw
ON embedding USING hnsw (vector vector_cosine_ops);

CREATE INDEX IF NOT EXISTS idx_chat_session_doc_id
ON chat_session(doc_id);

-- Timeline: chat list sidebar, most recently active first
CREATE INDEX IF NOT EXISTS idx_chat_session_user_recent
ON chat_session(user_id, updated_at DESC);

-- Timeline: ordered paging, jump-to-time, and history loading.
-- Replaces the old idx_message_session_id.
CREATE INDEX IF NOT EXISTS idx_message_session_time
ON message(session_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_message_role_id
ON message(role_id);

CREATE INDEX IF NOT EXISTS idx_citation_message_id
ON citation(message_id);

CREATE INDEX IF NOT EXISTS idx_citation_chunk_id
ON citation(chunk_id);

-- user_id lookups are covered by uq_chat_session_access (user_id, session_id)
CREATE INDEX IF NOT EXISTS idx_chat_session_access_session_id
ON chat_session_access(session_id);

-- ---------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------

-- Bump chat_session.updated_at whenever a message is added,
-- so the sidebar ordering never depends on the app remembering to do it.
CREATE OR REPLACE FUNCTION touch_chat_session()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE chat_session
    SET updated_at = NEW.created_at
    WHERE id = NEW.session_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_message_touch_session ON message;
CREATE TRIGGER trg_message_touch_session
AFTER INSERT ON message
FOR EACH ROW EXECUTE FUNCTION touch_chat_session();

-- Keep document.updated_at current on edits
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_document_updated_at ON document;
CREATE TRIGGER trg_document_updated_at
BEFORE UPDATE ON document
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

